export function categoryLabel(language: Language, category: string) {
  if (language === "en") return category;
  return ({ Design: "Desain", Development: "Pengembangan", AI: "AI", Productivity: "Produktivitas", Business: "Bisnis", Utilities: "Utilitas" } as Record<string, string>)[category] ?? category;
}

